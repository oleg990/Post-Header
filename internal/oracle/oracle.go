// Package oracle — «предсказание дня»: одна добрая фраза в сутки,
// новая становится доступна каждый день в 9:00.
package oracle

import (
	"math/rand"
	"time"
)

// ResetHour — во сколько открывается новое предсказание.
const ResetHour = 9

// Day — ключ «дня предсказаний»: до 9:00 ещё идёт вчерашний день.
func Day(now time.Time) string {
	return now.Add(-ResetHour * time.Hour).Format("2006-01-02")
}

// Next — когда откроется следующее предсказание.
func Next(now time.Time) time.Time {
	t := time.Date(now.Year(), now.Month(), now.Day(), ResetHour, 0, 0, 0, now.Location())
	if !now.Before(t) {
		t = t.AddDate(0, 0, 1)
	}
	return t
}

// Pick выбирает фразу, которой ещё не было; когда показаны все, круг
// начинается заново. Возвращает номер фразы и обновлённый список показанных.
func Pick(seen []int, r *rand.Rand) (int, []int) {
	if len(seen) >= len(Phrases) {
		seen = nil
	}
	used := make(map[int]bool, len(seen))
	for _, i := range seen {
		used[i] = true
	}
	free := make([]int, 0, len(Phrases)-len(seen))
	for i := range Phrases {
		if !used[i] {
			free = append(free, i)
		}
	}
	i := free[r.Intn(len(free))]
	return i, append(seen, i)
}

